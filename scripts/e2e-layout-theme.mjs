const steps = []
const add = (step) => steps.push(step)
const js = (code, wait=180) => add({js:code,wait})
const check = (label, expression) => js(`(()=>{if(!(${expression})) throw new Error(${JSON.stringify(label)});return ${JSON.stringify(label)}})()`)
const size = (width,height) => add({size:[width,height],wait:180})
js(`(async()=>{const d=new Date();d.setHours(10,15,0,0);const key=d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0');for(let i=0;i<3;i++)await window.api.tasks.create({title:'时间重叠测试'+i,scheduledDate:key,dueAt:d.toISOString()});await window.api.tasks.create({title:'全天安排测试',scheduledDate:key})})()`,300)
js(`[...document.querySelectorAll('.nav-item')].find(x=>x.textContent.includes('日历')).click()`,300)
js(`document.querySelectorAll('.calendar-modes button')[1].click()`,300)
check('七天时间轴', `document.querySelectorAll('.week-column').length===7 && document.querySelectorAll('.week-hours span').length===24`)
check('全天及定时分区', `document.querySelector('.week-all-day').textContent.includes('全天安排测试') && document.querySelectorAll('.week-event .week-task').length===3`)
check('同一时段任务纵向堆叠', `document.querySelectorAll('.week-event').length===1 && document.querySelector('.week-event').getBoundingClientRect().height>=60`)
js(`document.querySelector('.week-column.selected').dispatchEvent(new MouseEvent('dblclick',{bubbles:true,clientY:document.querySelector('.week-column.selected').getBoundingClientRect().top+11*44+5}))`,200)
check('双击时间段带入时间', `/[0-9]{1,2}:00 $/.test(document.querySelector('.qa-input')?.value ?? '')`)
js(`document.querySelector('.qa .icon-btn').click()`)
size(1280,820)
add({shot:resolve('.shots/week-0.2.1.png')})
for(const [width,height] of [[1440,900],[1100,700],[860,640],[720,520]]) {
 size(width,height)
 check(`${width}窗口没有页面水平溢出`, `document.documentElement.scrollWidth<=innerWidth && document.querySelector('.main').getBoundingClientRect().width>500`)
 check(`${width}工具栏可见`, `[...document.querySelectorAll('.calendar-modes button,.cal-nav button,.cal-nav input')].every(e=>{const r=e.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.bottom<=innerHeight})`)
 check(`${width}时间轴可滚动`, `document.querySelector('.week-scroll').clientHeight>100 && document.querySelector('.week-scroll').scrollHeight>document.querySelector('.week-scroll').clientHeight`)
}
add({shot:resolve('.shots/packaged-small-diagnostic.png')})
add({inspectWindow:true})
check('窄窗口侧栏折叠', `getComputedStyle(document.querySelector('.sidebar')).display==='none' && getComputedStyle(document.querySelector('.navigation-toggle')).display!=='none'`)
js(`document.querySelector('.navigation-toggle').click()`)
check('窄窗口可打开导航', `getComputedStyle(document.querySelector('.sidebar')).display!=='none'`)
js(`document.querySelector('.sidebar-backdrop').click()`)
js(`document.querySelector('.week-event .week-task').click()`,450)
check('窄窗口详情位于窗口内', `(()=>{const r=document.querySelector('.detail').getBoundingClientRect();return r.right<=innerWidth&&r.left>=0&&r.height>300})()`)
js(`document.querySelector('.detail-head button').click()`)
add({shot:resolve('.shots/week-small-0.2.1.png')})
js(`(async()=>{delete document.documentElement.dataset.theme;await window.api.app.setTheme('system')})()`)
add({nativeThemeSource:'dark',wait:250})
