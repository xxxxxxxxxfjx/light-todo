add({nativeThemeSource:'light',wait:250})
add({inspectWindow:true})
check('系统浅色变化同步页面', `getComputedStyle(document.querySelector('.titlebar')).backgroundColor==='rgb(243, 243, 245)'`)
js(`document.querySelector('.sb-foot .nav-item').click()`,250)
js(`[...document.querySelectorAll('.settings .seg')].find(x=>x.textContent==='深色').click()`,250)
check('设置深色同步应用与原生标题栏', `document.documentElement.dataset.theme==='dark' && getComputedStyle(document.querySelector('.titlebar')).backgroundColor==='rgb(28, 28, 32)'`)
add({inspectWindow:true})
js(`document.querySelector('.settings-head button').click()`)
async function run(name, testSteps){
 const spec=join(dir,name+'.json');writeFileSync(spec,JSON.stringify({steps:testSteps}))
 const packaged=process.argv[2];const env={...process.env,LIGHTTODO_DATA_DIR:dir};delete env.ELECTRON_RUN_AS_NODE
 const exe=resolve(packaged??'node_modules/electron/dist/electron.exe')
 const child=spawn(exe,[...(packaged?[]:['.','--no-sandbox','--disable-gpu']),`--e2e=${spec}`],{env,stdio:'ignore'})
 await new Promise((ok,fail)=>{const timer=setTimeout(()=>{child.kill();fail(new Error('测试超时'))},90000);child.on('exit',()=>{clearTimeout(timer);ok()});child.on('error',e=>{clearTimeout(timer);fail(e)})})
 const out=JSON.parse(readFileSync(spec.replace('.json','.out.json'),'utf8'));assert.equal(out.ok,true,out.error)
 return out.results
}
const result=await run('layout-theme',steps)
const overlays=result.filter(x=>x?.overlay).map(x=>x.overlay.color)
assert.deepEqual(overlays.slice(-3),['#1c1c20','#f3f3f5','#1c1c20'])
assert.deepEqual(result.find(x=>x?.size?.[0]===720)?.size,[720,520])
